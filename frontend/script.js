/* CART */

function addToCart(id){

    const product = PRODUCTS.find(
        p => Number(p.id) === Number(id)
    );

    if(!product){
        alert("Product not found");
        return;
    }

    const found = cart.find(
        x => Number(x.id) === Number(product.id)
    );

    if(found){

        found.qty++;

    }else{

        cart.push({
            id: Number(product.id),
            name: product.name,
            qty: 1
        });

    }

    saveCart();

    const drawer = document.getElementById("drawer");

    if(drawer && drawer.classList.contains("open")){
        renderCart();
    }else{
        openCart();
    }
}


function saveCart(){

    localStorage.setItem(
        "vj_cart",
        JSON.stringify(cart)
    );

    const count=
        document.getElementById("cartCount");

    if(count){

        count.textContent=
            cart.reduce(
                (a,b)=>a+b.qty,
                0
            );

    }

}


function renderCart(){

    const box=
        document.getElementById("cartItems");

    if(!box)return;

    if(!cart.length){

        box.innerHTML=
            '<div class="empty">Your cart is empty 🛒</div>';

        const totalBox=
            document.getElementById("cartTotal");

        if(totalBox){

            totalBox.textContent="₹0";

        }

        return;

    }

    let total=0;

    box.innerHTML=

        cart.map(item=>{

            const p=
                PRODUCTS.find(
                    x=>x.id===item.id
                );

            if(!p)return "";

            const sub=
                p.price*item.qty;

            total+=sub;

            return `

                <div class="cartitem">

                    <div>

                        <b>
                            ${p.name}
                        </b>

                        <small>
                            ${money(p.price)} each
                        </small>

                    </div>

                    <div class="qty">

                        <button
                            onclick="changeQty(${p.id},-1)">
                            −
                        </button>

                        <b>
                            ${item.qty}
                        </b>

                        <button
                            onclick="changeQty(${p.id},1)">
                            +
                        </button>

                    </div>

                </div>

            `;

        }).join("");

    const totalBox=
        document.getElementById("cartTotal");

    if(totalBox){

        totalBox.textContent=
            money(total);

    }

}


function changeQty(id,d){

    const item=
        cart.find(x=>x.id===id);

    if(!item)return;

    item.qty+=d;

    if(item.qty<=0){

        cart=
            cart.filter(
                x=>x.id!==id
            );

    }

    saveCart();

    renderCart();

}


/* OPEN / CLOSE CART */

function openCart(){

    const drawer=
        document.getElementById("drawer");

    if(drawer){

        drawer.classList.add("open");

    }

    renderCart();

}


function closeCart(){

    const drawer=
        document.getElementById("drawer");

    if(drawer){

        drawer.classList.remove("open");

    }

}


